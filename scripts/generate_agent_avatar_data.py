"""Regenerate static terminal sprites from CodeIsland mascot GIF first frames.

This maintenance script needs Pillow; the game itself does not.
"""

from pathlib import Path
from pprint import pformat

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "ai_avatars" / "codeisland"
OUTPUT = ROOT / "texas_holdem" / "ui" / "ai_avatar_data.py"
NAMES = ("claude", "codex", "gemini", "cursor", "opencode", "qoder")
SYMBOLS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
WIDTH = 24
HEIGHT = 18


def sprite_from_gif(path: Path) -> dict:
    with Image.open(path) as gif:
        frame = gif.convert("RGBA")
    artwork = frame.crop(frame.getbbox())
    scaled_height = round(artwork.height * WIDTH / artwork.width)
    artwork = artwork.resize((WIDTH, scaled_height), Image.Resampling.NEAREST)
    canvas = Image.new("RGBA", (WIDTH, HEIGHT))
    canvas.paste(artwork, (0, (HEIGHT - scaled_height) // 2))

    colors = sorted({
        canvas.getpixel((x, y))[:3]
        for y in range(HEIGHT)
        for x in range(WIDTH)
        if canvas.getpixel((x, y))[3]
    })
    if len(colors) > len(SYMBOLS):
        raise ValueError(f"Too many colors in {path.name}: {len(colors)}")
    color_keys = {color: SYMBOLS[index] for index, color in enumerate(colors)}
    palette = {key: "#{:02x}{:02x}{:02x}".format(*color) for color, key in color_keys.items()}
    rows = tuple(
        "".join(
            color_keys[canvas.getpixel((x, y))[:3]] if canvas.getpixel((x, y))[3] else "."
            for x in range(WIDTH)
        )
        for y in range(HEIGHT)
    )
    return {"palette": palette, "rows": rows}


def main() -> None:
    sprites = {name: sprite_from_gif(SOURCE / f"{name}.gif") for name in NAMES}
    output = (
        '"""CodeIsland mascot first frames sampled for 24x18 terminal sprites.\n\n'
        "Generated by scripts/generate_agent_avatar_data.py from MIT-licensed GIFs\n"
        'in assets/ai_avatars/codeisland. Do not edit this file by hand."""\n\n'
        f"SPRITES = {pformat(sprites, width=100, sort_dicts=False)}\n"
    )
    OUTPUT.write_text(output)


if __name__ == "__main__":
    main()
