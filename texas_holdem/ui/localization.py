_ENGLISH_REPLACEMENTS = sorted(ENGLISH.items(), key=lambda item: len(item[0]), reverse=True)
_ENGLISH_PUNCTUATION = str.maketrans({
    "，": ",", "：": ":", "。": ".", "（": "(", "）": ")", "、": ",", "？": "?",
})


def translate(value):
    if not isinstance(value, str):
        return value
    text = value
    protected = {}
    for index, name in enumerate(sorted(PRESERVED_NAMES, key=len, reverse=True)):
        marker = f"\x00NAME{index}\x00"
        pattern = rf"(?<![\w]){re.escape(name)}(?=$|[\s:：，。,.!?])"
        text, count = re.subn(pattern, lambda match: marker, text)
        if count:
            protected[marker] = name
    text = _EMOJI.sub("", text)
    if LANGUAGE == "en":
        text = re.sub(r"第\s+(\d+)\s+手牌", r"Hand \1", text)
        for source, target in _ENGLISH_REPLACEMENTS:
            text = text.replace(source, target)
        text = re.sub(r"\bHand (\d+) Hand\b", r"Hand \1", text)
        text = text.translate(_ENGLISH_PUNCTUATION)
    elif ACTIVE:
        text = text.replace("(y/n/back)", "(是/否/返回)").replace("(y/n)", "(是/否)")
        text = text.replace("b=上一步, s=玩家风格, q=退出", "上一步/风格/退出")
        text = text.replace("b=重新开始, q=退出", "重新开始/退出")
    for marker, name in protected.items():
        text = text.replace(marker, name)
    return text


@contextmanager
def terminal_language(language):
    """Translate terminal print/input calls for the duration of a game session."""
    global LANGUAGE, ACTIVE, PRESERVED_NAMES
    if language not in {"zh", "en"}:
        raise ValueError("language must be zh or en")
    previous_language = LANGUAGE
    previous_active = ACTIVE
    previous_names = PRESERVED_NAMES
    original_print = builtins.print
    original_input = builtins.input
    LANGUAGE = language
    ACTIVE = True
    PRESERVED_NAMES = set()

    def localized_print(*values, **kwargs):
        original_print(*(translate(value) for value in values), **kwargs)

    def localized_input(prompt=""):
        answer = original_input(translate(prompt))
        if "姓名" in prompt and answer.strip():
            PRESERVED_NAMES.add(answer.strip())
        return answer

    builtins.print = localized_print
    builtins.input = localized_input
    try:
        yield
    finally:
        builtins.print = original_print
        builtins.input = original_input
        LANGUAGE = previous_language
        ACTIVE = previous_active
        PRESERVED_NAMES = previous_names
