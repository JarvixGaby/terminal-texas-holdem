def action_label(action):
    """Display localized commands without changing internal action values."""
    if not ACTIVE or LANGUAGE != "zh":
        return action
    return {
        "check": "过牌", "call": "跟注", "raise": "加注",
        "bet": "下注", "fold": "弃牌", "status": "状态", "help": "帮助",
        "avatars": "头像",
    }.get(action, action)


def choose_language():
    """Ask before the first game message. The prompt is bilingual by design."""
    while True:
        answer = builtins.input("选择语言 / Choose language: 1. 中文  2. English > ").strip().lower()
        if answer in {"1", "中文", "zh", "zh-cn"}:
            return "zh"
        if answer in {"2", "english", "en"}:
            return "en"
        builtins.print("请输入 1 或 2 / Please enter 1 or 2.")


